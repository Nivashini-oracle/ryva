# STEP m-3: build the real GREEN / AMBER / RED layouts (not just colours)
# ---------------------------------------------------------------------------
def make_green_page():
    page = QWidget()
    page.setStyleSheet(f"background-color: {COLORS['GREEN']};")
    layout = QGridLayout()
    page.setLayout(layout)

    readouts = ["RPM", "Load", "Temp", "Vib", "CLS", "Time"]
    fake_values = ["1840", "3.2 t", "31 C", "OK", "18", "09:41"]

    page.value_labels = {}
    for i, (name, val) in enumerate(zip(readouts, fake_values)):
        row, col = divmod(i, 3)
        label = QLabel(name)
        label.setStyleSheet("color: #9fdca0; font-size: 16px;")
        value = QLabel(val)
        value.setStyleSheet("color: white; font-size: 24px; font-weight: bold;")
        value.setAlignment(Qt.AlignmentFlag.AlignCenter)
        cell_layout = QVBoxLayout()
        cell_layout.addWidget(label, alignment=Qt.AlignmentFlag.AlignCenter)
        cell_layout.addWidget(value)
        wrapper = QWidget()
        wrapper.setLayout(cell_layout)
        layout.addWidget(wrapper, row, col)
        page.value_labels[name] = value

    return page


